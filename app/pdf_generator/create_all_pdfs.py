def extract_chapters(ts_content):
    """Extract chapters from TypeScript file"""
    chapters = []
    # Try single-quoted title first
    chapter_blocks = re.findall(
        r"\{\s*number:\s*(\d+),\s*title:\s*'([^']+)',\s*content:\s*`\s*(.*?)`\s*\}",
        ts_content,
        re.DOTALL
    )
    if not chapter_blocks:
        # Try double-quoted title
        chapter_blocks = re.findall(
            r'\{\s*number:\s*(\d+),\s*title:\s*"([^"]+)",\s*content:\s*`\s*(.*?)`\s*\}',
            ts_content,
            re.DOTALL
        )
    for match in chapter_blocks:
        chapters.append({
            'number': int(match[0]),
            'title': match[1],
            'content': match[2].strip()
        })
    return chapters

